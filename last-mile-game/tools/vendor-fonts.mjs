// Copies the game's font files from @fontsource packages into
// last-mile/vendor/fonts and writes fonts.css (called by tools/vendor.sh).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'last-mile', 'vendor', 'fonts');
const SUBSETS = ['latin', 'latin-ext'];

// family -> [package, [[weight, style], ...]]  (what style.css and the old Google URL asked for)
const FONTS = {
  'Barlow': ['barlow', [[500, 'normal'], [600, 'normal'], [700, 'normal'], [800, 'normal'], [900, 'normal'], [700, 'italic']]],
  'Bebas Neue': ['bebas-neue', [[400, 'normal']]],
  'Bungee': ['bungee', [[400, 'normal']]],
  'Chakra Petch': ['chakra-petch', [[600, 'normal'], [700, 'normal'], [700, 'italic']]],
  'Russo One': ['russo-one', [[400, 'normal']]],
  // Comic callouts: Bangers for big lettering, Comic Neue for bubble text.
  'Bangers': ['bangers', [[400, 'normal']]],
  'Comic Neue': ['comic-neue', [[700, 'normal']]],
};

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
let css = '/* Generated by tools/vendor-fonts.mjs from @fontsource. Do not edit. */\n';
let bytes = 0;

for (const [family, [pkg, variants]] of Object.entries(FONTS)) {
  const base = path.join(ROOT, 'node_modules', '@fontsource', pkg);
  const unicode = JSON.parse(fs.readFileSync(path.join(base, 'unicode.json'), 'utf8'));
  fs.copyFileSync(path.join(base, 'LICENSE'), path.join(OUT, `OFL-${pkg}.txt`));
  for (const [weight, style] of variants) {
    for (const subset of SUBSETS) {
      // Some families ship latin only (Comic Neue); the browser then takes
      // the missing glyphs, ₹ included, from the next font in the stack.
      if (!unicode[subset]) continue;
      const file = `${pkg}-${subset}-${weight}-${style}.woff2`;
      fs.copyFileSync(path.join(base, 'files', file), path.join(OUT, file));
      bytes += fs.statSync(path.join(OUT, file)).size;
      css += `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;`
        + `src:url(${file}) format('woff2');unicode-range:${unicode[subset]};}\n`;
    }
  }
}
fs.writeFileSync(path.join(OUT, 'fonts.css'), css);
console.log(`Vendored fonts -> ${OUT} (${(bytes / 1024).toFixed(0)} KB woff2)`);
